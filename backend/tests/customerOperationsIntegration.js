import assert from "node:assert/strict";
import { test } from "node:test";
import { randomUUID } from "node:crypto";
import express from "express";
import jwt from "jsonwebtoken";
import { withIsolatedMongo } from "./helpers/isolatedMongo.js";
import supportRoutes from "../routes/supportRoutes.js";
import tableRoutes from "../routes/tableRoutes.js";
import menuRoutes from "../routes/menuRoutes.js";
import orderRoutes from "../routes/orderRoutes.js";
import kitchenRoutes from "../routes/kitchenRoutes.js";
import authRoutes from "../routes/authRoutes.js";
import cartRoutes from "../routes/cartRoutes.js";
import categoryRoutes from "../routes/categoryRoutes.js";
import settingsRoutes from "../routes/restaurantSettingsRoutes.js";
import profileRoutes from "../routes/profileRoutes.js";
import rewardRoutes from "../routes/rewardRoutes.js";
import User from "../models/User.js";
import Order from "../models/Order.js";
import MenuItem from "../models/MenuItem.js";
import InventoryRecipe from "../models/InventoryRecipe.js";
import InventoryCategory from "../models/InventoryCategory.js";
import InventoryItem from "../models/InventoryItem.js";
import StockTransaction from "../models/StockTransaction.js";
import DiningTable from "../models/DiningTable.js";
import OrderSupport from "../models/OrderSupport.js";
import { csrfProtection } from "../middleware/security.js";
import { supportInput } from "../services/orderSupportService.js";

process.env.NODE_ENV = "test";
process.env.JWT_SECRET = "customer-operations-owned-test-secret-only";
process.env.ALLOW_NON_TRANSACTIONAL_INVENTORY = "false";

test("support, table QR and cart suggestions use existing order rules (owned replica set)", { timeout: 240000 }, async t => withIsolatedMongo(async () => {
  const actors = {};
  for (const [name, role] of [["admin", "admin"], ["manager", "manager"], ["cashier", "cashier"], ["kitchen", "kitchen"], ["customer", "customer"], ["other", "customer"]]) actors[name] = await User.create({ name: `Test ${name}`, email: `${name}@customer-operations.test`, role, password: "TestPassword123!", phone: "0500000000" });
  const tokens = Object.fromEntries(Object.entries(actors).map(([name, user]) => [name, jwt.sign({ id: String(user._id), sv: 0 }, process.env.JWT_SECRET)]));
  const dish = await MenuItem.create({ name: "Fixture Burger", description: "Owned fixture", category: "Food", price: 20, image: "/pwa/icon-192.png" });
  const fries = await MenuItem.create({ name: "Fixture Fries", description: "Owned fixture", category: "Food", price: 5, image: "/pwa/icon-192.png" });
  const drink = await MenuItem.create({ name: "Fixture Drink", description: "Owned fixture", category: "Food", price: 3, image: "/pwa/icon-192.png", customization: { enabled: true, spice: { enabled: true, options: ["mild", "hot"], default: "mild" } } });
  const unavailable = await MenuItem.create({ name: "Unavailable fixture", description: "Owned fixture", category: "Food", price: 5, image: "/pwa/icon-192.png", isAvailable: false });
  const unconfigured = await MenuItem.create({ name: "Unconfigured fixture", description: "Owned fixture", category: "Food", price: 5, image: "/pwa/icon-192.png" });
  const category = await InventoryCategory.create({ name: "Fixture ingredients", skuPrefix: "FX" });
  const ingredient = await InventoryItem.create({ name: "Empty fixture stock", sku: "FX-001", category: category._id, unit: "kg" });
  const soldOut = await MenuItem.create({ name: "Sold out fixture", description: "Owned fixture", category: "Food", price: 5, image: "/pwa/icon-192.png" });
  await InventoryRecipe.create({ menuItem: soldOut._id, ingredients: [{ inventoryItem: ingredient._id, quantityPerSale: 1, unit: "kg" }], updatedBy: actors.admin._id });
  for (const product of [dish, fries, drink, unavailable]) await InventoryRecipe.create({ menuItem: product._id, doNotTrack: true, updatedBy: actors.admin._id });
  const app = express(); app.use(express.json(), csrfProtection);
  for (const [name, router] of [["support", supportRoutes], ["tables", tableRoutes], ["menu", menuRoutes], ["orders", orderRoutes], ["kitchen", kitchenRoutes], ["auth", authRoutes], ["cart", cartRoutes], ["categories", categoryRoutes], ["settings", settingsRoutes], ["profile", profileRoutes], ["rewards", rewardRoutes]]) app.use(`/api/${name}`, router);
  app.get("/api/combos", (_req, res) => res.json({ success: true, data: [] }));
  app.use((error, _req, res, _next) => res.status(error.status || 500).json({ message: error.message }));
  const server = await new Promise(resolve => { const instance = app.listen(0, "127.0.0.1", () => resolve(instance)); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  const api = async (role, resource, body, method = body === undefined ? "GET" : "POST", headers = {}) => {
    const response = await fetch(origin + "/api" + resource, { method, headers: { "Content-Type": "application/json", ...(role ? { Authorization: `Bearer ${tokens[role]}` } : {}), ...headers }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: response.status, body: await response.json() };
  };
  const cart = [{ productId: String(dish._id), quantity: 1 }];
  const orderBody = () => ({ idempotencyKey: randomUUID(), orderType: "dine-in", customer: { name: "Fixture Customer", phone: "0500000000" }, items: cart });
  let table, tableToken, ownedOrder, guestOrder, guestToken;
  try {
    await t.test("table administration, secret QR links and invalid/inactive resolution", async () => {
      for (const role of [null, "customer", "cashier", "kitchen"]) assert.ok([401, 403].includes((await api(role, "/tables")).status));
      const created = await api("admin", "/tables", { code: "t-01", name: "Window table" });
      assert.equal(created.status, 201, JSON.stringify(created.body)); table = created.body.data;
      assert.equal(table.code, "T-01"); assert.equal("qrToken" in table, false);
      assert.equal((await api("manager", "/tables", { code: "t-01", name: "Duplicate" })).status, 409);
      const list = await api("manager", "/tables"); assert.equal(list.body.data[0].qrToken, undefined); assert.equal(list.body.data[0].qrTokenHash, undefined);
      const qr = await api("admin", `/tables/${table._id}/qr`); tableToken = new URL(qr.body.data.path, origin).searchParams.get("table");
      assert.equal((await api(null, "/tables/resolve", { token: tableToken })).body.data.code, "T-01");
      assert.equal((await api(null, "/tables/resolve", { token: "bad" })).status, 404);
      assert.equal((await api(null, "/tables/resolve", { token: "a".repeat(43) })).status, 409);
      assert.equal((await api("customer", `/tables/${table._id}/qr`)).status, 403);
    });
    await t.test("QR orders preserve unpaid state, table snapshots, idempotency and kitchen visibility", async () => {
      const body = { ...orderBody(), tableToken };
      const created = await api("customer", "/orders", body);
      assert.equal(created.status, 201, JSON.stringify(created.body)); ownedOrder = created.body.data;
      assert.equal(ownedOrder.diningTable.code, "T-01"); assert.equal(ownedOrder.paymentStatus, "pending");
      assert.equal(ownedOrder.totalAmount, 20); assert.equal(ownedOrder.status, "pending");
      assert.equal((await api("customer", "/orders", body)).status, 200);
      const changed = await api("customer", "/orders", { ...body, tableToken: "b".repeat(43) }); assert.equal(changed.status, 409);
      const kitchen = await api("kitchen", "/kitchen/orders"); assert.equal(kitchen.body.data.find(row => row._id === ownedOrder._id).diningTable.code, "T-01");
      const quote = await api(null, "/orders/quote", { fulfillmentType: "dine_in", tableToken, items: cart }); assert.equal(quote.status, 200); assert.equal(quote.body.data.total, 20);
      assert.equal((await api(null, "/orders", { ...orderBody(), tableId: table._id })).status, 400);
      assert.equal((await api(null, "/orders", { ...orderBody(), diningTable: { code: "FAKE" } })).status, 400);
      assert.equal((await api(null, "/orders", { ...orderBody(), orderType: "pickup", tableToken })).status, 400);
      assert.equal((await api(null, "/orders", { ...orderBody(), tableToken: "invalid" })).status, 404);
      await api("admin", `/tables/${table._id}`, { code: "T-01", name: "Renamed table", isActive: false }, "PATCH");
      assert.equal((await api(null, "/tables/resolve", { token: tableToken })).status, 409);
      assert.equal((await api(null, "/orders", { ...orderBody(), tableToken })).status, 409);
      assert.equal((await api("customer", "/orders", body)).status, 200, "A committed order remains recoverable after deactivation");
      assert.equal((await Order.findById(ownedOrder._id)).diningTable.name, "Window table");
      await api("admin", `/tables/${table._id}`, { code: "T-01", name: "Window table", isActive: true }, "PATCH");
      const guest = await api(null, "/orders", orderBody()); assert.equal(guest.status, 201); guestOrder = guest.body.data; guestToken = guest.body.trackingToken;
    });
    await t.test("complaints enforce ownership, validation, duplicate protection and private notes", async () => {
      const resource = `/support/orders/${ownedOrder.orderNumber}`;
      for (const role of [null, "other", "cashier"]) assert.equal((await api(role, resource)).status, 404);
      assert.throws(() => supportInput({ category: "Missing item", description: "Missing my food", affectedItems: [99] }, ownedOrder), /valid order items/);
      assert.throws(() => supportInput({ category: "Missing item", description: "Missing my food" }, ownedOrder), /affected order items/);
      const before = await Order.findById(ownedOrder._id).lean(), ledger = await StockTransaction.countDocuments();
      const complaint = { category: "Missing item", description: "My burger was missing from this order", affectedItems: [0] };
      const duplicates = await Promise.all([api("customer", resource, complaint), api("customer", resource, complaint)]);
      assert.deepEqual(duplicates.map(row => row.status).sort(), [201, 409]);
      const id = duplicates.find(row => row.status === 201).body.data._id;
      assert.equal((await api("customer", `/support/${id}`)).status, 403);
      assert.equal((await api("cashier", "/support")).status, 403);
      assert.equal((await api("manager", "/support?status=Open&search=" + encodeURIComponent(ownedOrder.orderNumber))).body.data.length, 1);
      assert.equal((await api("admin", `/support/${id}/messages`, { status: "Resolved", text: "Reviewing" })).status, 400);
      assert.equal((await api("admin", `/support/${id}/messages`, { text: "Private kitchen investigation", internal: true, status: "In Progress" })).status, 200);
      assert.equal((await api("customer", resource)).body.data.messages.length, 0);
      assert.equal((await api("manager", `/support/${id}`)).body.data.messages[0].internal, true);
      assert.equal((await api("customer", resource + "/messages", { text: "Please check the packaging", internal: true, status: "Closed" })).status, 200);
      const reply = await api("customer", resource); assert.equal(reply.body.data.messages[0].authorType, "Customer"); assert.equal(reply.body.data.status, "In Progress");
      assert.equal((await api("admin", `/support/${id}/messages`, { text: "We contacted you", status: "Closed", resolution: "Replacement arranged with the customer" })).status, 200);
      assert.equal((await api("customer", resource + "/messages", { text: "Another reply" })).status, 409);
      const visible = (await api("customer", resource)).body.data;
      assert.ok(!JSON.stringify(visible).includes("Private kitchen investigation")); assert.equal(visible.resolution, "Replacement arranged with the customer");
      const after = await Order.findById(ownedOrder._id).lean();
      for (const key of ["status", "paymentStatus", "totalAmount", "inventoryStatus", "refundedAmount"]) assert.deepEqual(after[key], before[key], key);
      assert.equal(await StockTransaction.countDocuments(), ledger);
      assert.equal(await OrderSupport.countDocuments({ order: ownedOrder._id }), 1);
    });
    await t.test("guest support reuses the private tracking code, including read/reply protection", async () => {
      const resource = `/support/orders/${guestOrder.orderNumber}`, headers = { "X-Order-Tracking-Token": guestToken };
      assert.equal((await api(null, resource)).status, 404);
      assert.equal((await api(null, resource, undefined, "GET", { "X-Order-Tracking-Token": "wrong" })).status, 404);
      const created = await api(null, resource, { category: "Other issue", description: "Please help with my guest order" }, "POST", headers); assert.equal(created.status, 201);
      assert.equal((await api(null, resource, undefined, "GET", headers)).body.data._id, created.body.data._id);
      assert.equal((await api(null, resource + "/messages", { text: "More information from guest" }, "POST", headers)).status, 200);
    });
    await t.test("curated suggestions exclude duplicates, unavailable, sold-out and unconfigured items", async () => {
      const ids = [fries, drink, unavailable, unconfigured, soldOut].map(row => String(row._id));
      assert.equal((await api("customer", `/menu/${dish._id}`, { complementaryItems: ids }, "PUT")).status, 403);
      assert.equal((await api("manager", `/menu/${dish._id}`, { complementaryItems: [...ids, String(dish._id)] }, "PUT")).status, 400);
      assert.equal((await api("manager", `/menu/${dish._id}`, { complementaryItems: ids }, "PUT")).status, 200);
      const suggestions = await api(null, "/menu/suggestions", { items: [{ productId: String(dish._id) }] });
      assert.equal(suggestions.status, 200, JSON.stringify(suggestions.body)); assert.deepEqual(suggestions.body.data.map(row => row.name), [fries.name, drink.name]);
      assert.equal(suggestions.body.data[0].price, 5); assert.equal(suggestions.body.data[1].customization.enabled, true);
      const excluded = await api(null, "/menu/suggestions", { items: [{ productId: String(dish._id) }, { productId: String(fries._id) }] }); assert.deepEqual(excluded.body.data.map(row => row.name), [drink.name]);
      assert.deepEqual((await api(null, "/menu/suggestions", { items: [] })).body.data, []);
      assert.equal((await api(null, "/menu/suggestions", { items: [{ productId: { $ne: null } }] })).status, 400);
      assert.equal((await api("customer", "/orders", { ...orderBody(), items: [{ productId: String(drink._id), quantity: 1, customization: { spiceLevel: "invalid" } }] })).status, 409);
      const repriced = await api("customer", "/orders", { ...orderBody(), items: [{ productId: String(fries._id), quantity: 1, price: 0.01 }] }); assert.equal(repriced.status, 201); assert.equal(repriced.body.data.totalAmount, 5);
    });
    if (process.env.RUN_CUSTOMER_OPERATIONS_BROWSER === "1") await t.test("desktop/mobile browser flows against the owned API and database", async () => {
      const { runCustomerOperationsBrowser } = await import("./helpers/customerOperationsBrowser.js");
      await runCustomerOperationsBrowser({ origin, tokens, dish, fries, drink, tableToken, api });
    });
  } finally { await new Promise(resolve => server.close(resolve)); }
}));
