        await page.waitForFunction(() => Array.from(document.querySelectorAll('[aria-label="Completion History"] button')).some(button => button.textContent === "Refresh records" && !button.disabled));
        const deniedHistoryRoute = resource => resource.pathname === "/api/planner/insights";
